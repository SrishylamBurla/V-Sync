import api from "../../services/api";
export const getFinancialSummary=async(params={})=>(await api.get("/finance/summary",{params})).data;
export const getExpenses=async(params={})=>(await api.get("/finance/expenses",{params})).data;
export const createExpense=async(payload)=>(await api.post("/finance/expenses",payload)).data;
export const getPettyCash=async(params={})=>(await api.get("/finance/petty-cash",{params})).data;
export const createPettyCash=async(payload)=>(await api.post("/finance/petty-cash",payload)).data;
export const getBulkAccounts=async()=>(await api.get("/finance/bulk-accounts")).data;
export const createBulkAccount=async(payload)=>(await api.post("/finance/bulk-accounts",payload)).data;
export const getBulkBillings=async()=>(await api.get("/finance/bulk-billing")).data;
export const createBulkBilling=async(payload)=>(await api.post("/finance/bulk-billing",payload)).data;
export const addBulkPayment=async(id,payload)=>(await api.post(`/finance/bulk-billing/${id}/payments`,payload)).data;
